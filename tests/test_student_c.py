"""Tests for the Student C (Trend Category) page.

Fixtures in tests/fixtures/student_c_*.json are real responses from the Student C API (generated by its
offline test harness), so the page is tested against what the service actually returns. The page is
run with Streamlit's ``AppTest`` to catch crashes, including when the API is down.
"""

import json
from pathlib import Path

import pytest
from streamlit.testing.v1 import AppTest

from app import main as core
from students import student_c as page

FIXTURES = Path(__file__).parent / "fixtures"
PREDICT = json.loads((FIXTURES / "student_c_predict.json").read_text())
FEATURES = json.loads((FIXTURES / "student_c_features.json").read_text())
METADATA = json.loads((FIXTURES / "student_c_model_metadata.json").read_text())


@pytest.fixture
def fake_tc_api(monkeypatch):
    class Fake:
        down = False
        degraded = False
        calls: list = []

        def __call__(self, base_url, path, payload=None):
            self.calls.append((path, payload))
            if self.down:
                return core.ApiResult(ok=False, error="The service could not be reached.")
            if path == "/predict":
                data = dict(PREDICT, token=payload["token"])
                if self.degraded:
                    data.update(missing_features=["Return20", "Return5", "TrendScore"],
                                peer_status={"student_a": "unavailable: HTTP 503", "student_b": "ok"})
                return core.ApiResult(ok=True, data=data)
            if path == "/features":
                return core.ApiResult(ok=True, data=FEATURES)
            if path == "/model-metadata":
                return core.ApiResult(ok=True, data=METADATA)
            return core.ApiResult(ok=False, error="Not Found (HTTP 404)", status=404)

    fake = Fake()
    fake.calls = []
    monkeypatch.setattr(core, "cached_call", fake)
    monkeypatch.setattr(core, "cached_call_many", lambda base, path, payloads: [fake(base, path, p) for p in payloads])
    monkeypatch.setattr(core, "health", lambda url, **k: core.ApiResult(ok=not fake.down, elapsed_seconds=0.2,
                                                                        error=None if not fake.down else "down"))
    monkeypatch.setattr(core, "api_url", lambda key: "https://example.invalid")
    return fake


# ------------------------------------------------------------ pure helpers
def test_labels_match_the_contract():
    assert page.TC_LABELS == ["Strong Downtrend", "Downtrend", "Sideways", "Uptrend", "Strong Uptrend"]
    assert METADATA["classification_labels"] == page.TC_LABELS


@pytest.mark.parametrize(("score", "label"), [(-0.1001, "Strong Downtrend"), (-0.10, "Downtrend"),
                                              (-0.02, "Sideways"), (0.02, "Sideways"), (0.0201, "Uptrend"),
                                              (0.10, "Uptrend"), (0.1001, "Strong Uptrend"), (None, None)])
def test_display_classification_boundaries(score, label):
    assert page.classify_score(score) == label


@pytest.mark.parametrize(("current", "forecast", "word"), [
    ("Uptrend", "Uptrend", "continue"), ("Downtrend", "Uptrend", "reversal"),
    ("Uptrend", "Strong Uptrend", "strengthen"), ("Strong Downtrend", "Downtrend", "ease"),
    ("Sideways", "Uptrend", "move"), (None, "Uptrend", "unavailable")])
def test_direction_change_wording(current, forecast, word):
    assert word in page.direction_change(current, forecast)


def test_helpers_on_the_real_response():
    probs = page.probabilities_frame(PREDICT)
    assert list(probs["Trend"]) == page.TC_LABELS and abs(probs["Probability"].sum() - 1) < 1e-3
    assert probs.loc[probs["Predicted"], "Trend"].item() == PREDICT["prediction"]
    assert set(page.importance_frame(METADATA)["key"]) == set(METADATA["features"])
    assert len(page.explanation_frame(PREDICT)) == len(PREDICT["explanation"])
    hist = page.history_frame(FEATURES["history"], keep_days=90)
    assert len(hist) == 90 and hist["TrendScore"].notna().all()
    assert page.format_value("Return20", None) == "missing"
    assert page.format_value("Volatility20", 0.0153) == "1.53% per day"


def test_history_trendscore_matches_api_current_value():
    """The display-only TrendScore recomputed from closes equals the API's value for the same day."""
    hist = page.history_frame(FEATURES["history"])
    assert hist["TrendScore"].iloc[-1] == pytest.approx(PREDICT["current"]["trend_score"], abs=1e-5)


# ------------------------------------------------------------ the page
def _run() -> AppTest:
    def script():
        from students import student_c

        student_c.render()

    app = AppTest.from_function(script, default_timeout=30).run()
    assert not app.exception, app.exception
    return app


def test_page_renders_required_outputs(fake_tc_api):
    app = _run()
    text = " ".join(m.value for m in app.markdown)
    assert "Current trend" in text and "Forecast trend" in text
    assert any(m.label == "Confidence" for m in app.metric)
    assert "Feature importance" in text


def test_page_offers_all_tokens(fake_tc_api):
    assert list(_run().selectbox(key="c_token").options) == [f"{t} - {n}" for t, n in core.TOKENS.items()]


def test_page_shows_degraded_mode(fake_tc_api):
    fake_tc_api.degraded = True
    assert any("degraded mode" in w.value for w in _run().warning)


def test_page_survives_api_outage(fake_tc_api):
    fake_tc_api.down = True
    app = _run()
    assert app.error, "an outage should be reported, not crash the page"
